"use client";

import { useState } from "react";
import type { Category, Property, Transaction } from "@/lib/domain/types";
import {
  categoriesFor,
  validateTransactionForm,
  type TransactionFormErrors,
  type TransactionFormValues,
} from "@/lib/domain/transaction-form";

export type TransactionInput = Omit<Transaction, "id" | "recurringId">;

interface Props {
  initial: TransactionFormValues;
  categories: Category[];
  properties: Property[];
  submitLabel: string;
  onSubmit: (value: TransactionInput) => Promise<void>;
  onDelete?: () => Promise<void>;
  /** Shown when the transaction was generated by a recurring rule. */
  recurringNote?: string;
}

const inputClass = "w-full rounded-lg border border-slate-300 bg-white px-3 py-3 text-base";
const labelClass = "mb-1 block text-sm font-medium text-slate-700";

export function TransactionForm({ initial, categories, properties, submitLabel, onSubmit, onDelete, recurringNote }: Props) {
  const [values, setValues] = useState(initial);
  const [errors, setErrors] = useState<TransactionFormErrors>({});
  const [busy, setBusy] = useState(false);
  const [saveError, setSaveError] = useState<string | null>(null);

  const available = categoriesFor(categories, values.propertyId);
  const selected = available.find((c) => c.id === values.categoryId);
  const set = (patch: Partial<TransactionFormValues>) => {
    setValues((v) => ({ ...v, ...patch }));
    // Hide the error of a field as soon as it is edited.
    setErrors((e) => {
      const next = { ...e };
      for (const key of Object.keys(patch)) delete next[key as keyof TransactionFormValues];
      return next;
    });
  };

  function changeProperty(propertyId: string) {
    // Keep the category only if it still fits the new scope.
    const keep = categoriesFor(categories, propertyId).some((c) => c.id === values.categoryId);
    set({ propertyId, categoryId: keep ? values.categoryId : "" });
  }

  async function run(action: () => Promise<void>) {
    setBusy(true);
    setSaveError(null);
    try {
      await action();
    } catch (e) {
      setSaveError(e instanceof Error ? e.message : String(e));
      setBusy(false);
    }
  }

  function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    const result = validateTransactionForm(values, categories);
    if (!result.ok) return setErrors(result.errors);
    setErrors({});
    void run(() => onSubmit(result.value));
  }

  function handleDelete() {
    if (!onDelete || !window.confirm("¿Eliminar este movimiento?")) return;
    void run(onDelete);
  }

  const income = available.filter((c) => c.type === "ingreso");
  const expense = available.filter((c) => c.type === "gasto");

  return (
    <form onSubmit={handleSubmit} noValidate className="space-y-4">
      {recurringNote && (
        <p className="rounded-lg bg-sky-50 px-3 py-2 text-sm text-sky-800">{recurringNote}</p>
      )}

      <div>
        <label htmlFor="tx-property" className={labelClass}>Piso</label>
        <select id="tx-property" className={inputClass} value={values.propertyId} onChange={(e) => changeProperty(e.target.value)}>
          <option value="">Personal</option>
          {properties.map((p) => <option key={p.id} value={p.id}>{p.name}</option>)}
        </select>
      </div>

      <div>
        <label htmlFor="tx-category" className={labelClass}>Categoría</label>
        <select
          id="tx-category"
          className={inputClass}
          value={values.categoryId}
          onChange={(e) => set({ categoryId: e.target.value })}
          aria-invalid={!!errors.categoryId}
        >
          <option value="">Elige una categoría</option>
          {income.length > 0 && (
            <optgroup label="Ingresos">
              {income.map((c) => <option key={c.id} value={c.id}>{c.name}</option>)}
            </optgroup>
          )}
          {expense.length > 0 && (
            <optgroup label="Gastos">
              {expense.map((c) => <option key={c.id} value={c.id}>{c.name}</option>)}
            </optgroup>
          )}
        </select>
        {selected && (
          <p className={`mt-1 text-sm ${selected.type === "gasto" ? "text-rose-700" : "text-emerald-700"}`}>
            {selected.type === "gasto" ? "Gasto" : "Ingreso"}
            {selected.deductible && " · deducible en la Renta"}
          </p>
        )}
        <FieldError message={errors.categoryId} />
      </div>

      <div className="grid grid-cols-2 gap-3">
        <div>
          <label htmlFor="tx-amount" className={labelClass}>Importe (€)</label>
          <input
            id="tx-amount"
            className={inputClass}
            inputMode="decimal"
            autoComplete="off"
            placeholder="0,00"
            value={values.amount}
            onChange={(e) => set({ amount: e.target.value })}
            aria-invalid={!!errors.amount}
          />
          <FieldError message={errors.amount} />
        </div>
        <div>
          <label htmlFor="tx-date" className={labelClass}>Fecha</label>
          <input
            id="tx-date"
            type="date"
            className={inputClass}
            value={values.date}
            onChange={(e) => set({ date: e.target.value })}
            aria-invalid={!!errors.date}
          />
          <FieldError message={errors.date} />
        </div>
      </div>

      <div>
        <label htmlFor="tx-concept" className={labelClass}>Concepto</label>
        <input
          id="tx-concept"
          className={inputClass}
          placeholder="Opcional"
          value={values.concept}
          onChange={(e) => set({ concept: e.target.value })}
        />
      </div>

      {saveError && <p className="text-sm text-rose-700">No se pudo guardar: {saveError}</p>}

      <button type="submit" disabled={busy} className="w-full rounded-lg bg-emerald-700 px-4 py-3 font-medium text-white disabled:opacity-50">
        {submitLabel}
      </button>
      {onDelete && (
        <button
          type="button"
          onClick={handleDelete}
          disabled={busy}
          className="w-full rounded-lg border border-rose-300 px-4 py-3 font-medium text-rose-700 disabled:opacity-50"
        >
          Eliminar
        </button>
      )}
    </form>
  );
}

function FieldError({ message }: { message?: string }) {
  return message ? <p className="mt-1 text-sm text-rose-700">{message}</p> : null;
}
