import { addMonths, dayInMonth, todayIso } from "@/lib/domain/dates";
import { annuityPayment } from "@/lib/domain/mortgage";
import { occurrenceTransactions, occurrencesBetween, planOf } from "@/lib/domain/recurring";
import type { Category, Property, Recurring, Snapshot, Transaction } from "@/lib/domain/types";
import { newId } from "./ids";

/**
 * Fictitious test data: 2 flats, the 6 full months before `today`'s month.
 * Names, addresses and amounts are made up.
 */
export const SEED_MONTHS = 6;

const euros = (value: number) => Math.round(value * 100);

type CategoryKey =
  | "alquiler" | "intereses" | "capital" | "ibi" | "comunidad" | "seguroHogar" | "seguroImpago"
  | "reparaciones" | "suministros" | "basuras" | "gestoria" | "otrosPiso"
  | "nomina" | "alimentacion" | "hogar" | "transporte" | "ocio" | "salud" | "otrosPersonal";

type SeedCategory = Omit<Category, "id" | "notExpense" | "limitedDeduction"> & Partial<Pick<Category, "notExpense" | "limitedDeduction">>;

const CATEGORIES: Record<CategoryKey, SeedCategory> = {
  alquiler: { name: "Alquiler", type: "ingreso", scope: "piso", deductible: false },
  intereses: { name: "Intereses hipoteca", type: "gasto", scope: "piso", deductible: true, limitedDeduction: true },
  // Paying off principal is money out, but not a deductible expense.
  capital: { name: "Amortización capital hipoteca", type: "gasto", scope: "piso", deductible: false, notExpense: true },
  ibi: { name: "IBI", type: "gasto", scope: "piso", deductible: true },
  comunidad: { name: "Comunidad", type: "gasto", scope: "piso", deductible: true },
  seguroHogar: { name: "Seguro hogar", type: "gasto", scope: "piso", deductible: true },
  seguroImpago: { name: "Seguro impago", type: "gasto", scope: "piso", deductible: true },
  reparaciones: { name: "Reparaciones y conservación", type: "gasto", scope: "piso", deductible: true, limitedDeduction: true },
  suministros: { name: "Suministros", type: "gasto", scope: "piso", deductible: true },
  basuras: { name: "Tasa de basuras", type: "gasto", scope: "piso", deductible: true },
  gestoria: { name: "Gestoría", type: "gasto", scope: "piso", deductible: true },
  otrosPiso: { name: "Otros", type: "gasto", scope: "piso", deductible: false },
  nomina: { name: "Nómina", type: "ingreso", scope: "personal", deductible: false },
  alimentacion: { name: "Alimentación", type: "gasto", scope: "personal", deductible: false },
  hogar: { name: "Hogar y suministros", type: "gasto", scope: "personal", deductible: false },
  transporte: { name: "Transporte", type: "gasto", scope: "personal", deductible: false },
  ocio: { name: "Ocio", type: "gasto", scope: "personal", deductible: false },
  salud: { name: "Salud", type: "gasto", scope: "personal", deductible: false },
  otrosPersonal: { name: "Otros personales", type: "gasto", scope: "personal", deductible: false },
};

export function createSeedData(today: string = todayIso()): Snapshot {
  const currentMonth = today.slice(0, 7);
  const months = Array.from({ length: SEED_MONTHS }, (_, i) => addMonths(currentMonth, i - SEED_MONTHS));
  const firstDay = dayInMonth(months[0], 1);

  const cat = Object.fromEntries(
    Object.entries(CATEGORIES).map(([key, value]) => [
      key,
      { notExpense: false, limitedDeduction: false, ...value, id: newId() },
    ]),
  ) as Record<CategoryKey, Category>;

  const centro: Property = {
    id: newId(),
    name: "Piso Centro",
    address: "Calle del Ejemplo 12, 3º B, Valladolid",
    purchaseDate: "2019-03-15",
    acquisitionPrice: euros(168000),
    purchaseCosts: euros(14280),
    cadastralValue: euros(96400),
    constructionPercentage: 62,
    active: true,
  };
  const playa: Property = {
    id: newId(),
    name: "Apartamento Playa",
    address: "Avenida Ficticia 4, 1º A, Gandía",
    purchaseDate: "2022-06-01",
    acquisitionPrice: euros(129500),
    purchaseCosts: euros(11650),
    cadastralValue: euros(71200),
    constructionPercentage: 55,
    active: true,
  };

  const transactions: Transaction[] = [];
  const recurrings: Recurring[] = [];
  const seedEnd = dayInMonth(months[SEED_MONTHS - 1], 31);

  const categoryById = (id: string) => Object.values(cat).find((c) => c.id === id)!;
  const add = (t: Omit<Transaction, "id" | "recurringId" | "type" | "confirmed">, recurringId: string | null = null) => {
    transactions.push({ ...t, id: newId(), type: categoryById(t.categoryId).type, recurringId, confirmed: true });
  };

  /**
   * Recurring rule plus its (confirmed) transactions within the seed period.
   * Occurrences from the current month on are generated by the app as pending.
   */
  const recurring = (
    r: Omit<Recurring, "id" | "type" | "endDate" | "generatedUntil" | "day" | "startDate" | "kind" | "mortgage">,
    monthIndex: number,
    day: number,
  ) => {
    const startDate = dayInMonth(months[monthIndex], day);
    const rule: Recurring = {
      ...r, id: newId(), kind: "fijo", mortgage: null, type: categoryById(r.categoryId).type, day, startDate, endDate: null, generatedUntil: seedEnd,
    };
    recurrings.push(rule);
    for (const date of occurrencesBetween(rule, null, seedEnd)) {
      add({ date, amount: rule.amount, categoryId: rule.categoryId, propertyId: rule.propertyId, concept: rule.concept }, rule.id);
    }
  };

  const monthly = (concept: string, amount: number, key: CategoryKey, property: Property | null, day: number) =>
    recurring({ concept, amount: euros(amount), categoryId: cat[key].id, propertyId: property?.id ?? null, frequency: "mensual" }, 0, day);
  const yearly = (monthIndex: number, day: number, amount: number, key: CategoryKey, property: Property, concept: string) =>
    recurring({ concept, amount: euros(amount), categoryId: cat[key].id, propertyId: property.id, frequency: "anual" }, monthIndex, day);

  monthly("Alquiler Piso Centro", 950, "alquiler", centro, 1);
  monthly("Alquiler Apartamento Playa", 780, "alquiler", playa, 5);
  monthly("Comunidad Piso Centro", 65, "comunidad", centro, 10);
  monthly("Comunidad Apartamento Playa", 48, "comunidad", playa, 10);
  monthly("Nómina", 2350, "nomina", null, 28);

  // Yearly charges (IBI in two instalments for Piso Centro).
  yearly(0, 20, 412.37, "ibi", centro, "IBI Piso Centro (1er plazo)");
  yearly(3, 20, 412.36, "ibi", centro, "IBI Piso Centro (2º plazo)");
  yearly(2, 15, 538.9, "ibi", playa, "IBI Apartamento Playa");
  yearly(1, 7, 286.4, "seguroHogar", centro, "Seguro hogar Piso Centro");
  yearly(4, 7, 214.75, "seguroHogar", playa, "Seguro hogar Apartamento Playa");
  yearly(1, 8, 315, "seguroImpago", centro, "Seguro de impago Piso Centro");
  yearly(2, 18, 96.8, "basuras", playa, "Tasa de basuras Apartamento Playa");

  // Mortgages: each installment split into interest (deductible) and principal (not an expense).
  const mortgage = (property: Property, principal: number, annualRate: number, installments: number, startDate: string) => {
    const day = Number(startDate.slice(8, 10));
    const endDate = dayInMonth(addMonths(startDate.slice(0, 7), installments - 1), day);
    const rule: Recurring = {
      id: newId(),
      kind: "hipoteca",
      concept: `Hipoteca ${property.name}`,
      amount: annuityPayment(euros(principal), annualRate, installments),
      type: "gasto",
      categoryId: cat.intereses.id,
      propertyId: property.id,
      frequency: "mensual",
      day,
      startDate,
      endDate,
      generatedUntil: seedEnd,
      mortgage: {
        principal: euros(principal), annualRate, installments, interestMethod: "mensual", principalCategoryId: cat.capital.id, adjustments: [],
      },
    };
    recurrings.push(rule);
    const plan = planOf(rule);
    for (const date of occurrencesBetween(rule, dayBefore(firstDay), seedEnd)) {
      for (const t of occurrenceTransactions(rule, date, true, plan)) transactions.push({ ...t, id: newId() });
    }
  };
  mortgage(centro, 120000, 2.9, 300, "2019-04-02");
  mortgage(playa, 95000, 3.4, 360, "2022-07-03");

  // One-off flat expenses.
  const flat = (monthIndex: number, day: number, amount: number, key: CategoryKey, property: Property, concept: string) =>
    add({ date: dayInMonth(months[monthIndex], day), amount: euros(amount), categoryId: cat[key].id, propertyId: property.id, concept });

  flat(2, 22, 180, "reparaciones", centro, "Fontanero: cambio de grifo y latiguillos");
  flat(4, 12, 345.5, "reparaciones", playa, "Pintura salón");
  flat(5, 25, 121, "gestoria", centro, "Gestoría: renovación contrato");
  flat(3, 6, 38.9, "suministros", playa, "Luz entre inquilinos");

  // Personal expenses.
  const personal: [number, number, number, CategoryKey, string][] = [];
  months.forEach((_, i) => {
    personal.push(
      [i, 3, 92.4 + i * 3.1, "alimentacion", "Supermercado"],
      [i, 17, 118.75 - i * 2.4, "alimentacion", "Supermercado"],
      [i, 9, 64.2 + (i % 3) * 7.5, "hogar", "Luz y gas"],
      [i, 11, 35, "hogar", "Fibra y móvil"],
      [i, 14, 45 + (i % 2) * 20, "transporte", "Gasolina"],
    );
  });
  personal.push(
    [0, 21, 58, "ocio", "Cena con amigos"],
    [2, 26, 124.9, "ocio", "Entradas concierto"],
    [3, 4, 42, "salud", "Farmacia"],
    [4, 19, 75, "salud", "Dentista: revisión"],
    [5, 15, 39.99, "otrosPersonal", "Regalo cumpleaños"],
  );
  for (const [i, day, amount, key, concept] of personal) {
    add({ date: dayInMonth(months[i], day), amount: euros(amount), categoryId: cat[key].id, propertyId: null, concept });
  }

  return { properties: [centro, playa], categories: Object.values(cat), transactions, recurrings };
}

/** `YYYY-MM-DD` of the previous day. */
function dayBefore(date: string): string {
  const d = new Date(date + "T00:00:00Z");
  d.setUTCDate(d.getUTCDate() - 1);
  return d.toISOString().slice(0, 10);
}
