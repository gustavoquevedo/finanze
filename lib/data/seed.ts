import { addMonths, dayInMonth, todayIso } from "@/lib/domain/dates";
import { annuityPayment } from "@/lib/domain/mortgage";
import { occurrenceTransactions, occurrencesBetween, planOf } from "@/lib/domain/recurring";
import type { Asset, AssetSnapshot, AssetType, Category, MortgageAdjustment, Portfolio, Property, Recurring, Snapshot, Transaction } from "@/lib/domain/types";
import { DEFAULT_ASSET_TYPES, DEFAULT_CATEGORIES, type DefaultCategoryKey } from "./defaults";
import { newId } from "./ids";

/**
 * Fictitious test data: 2 flats, the 6 full months before `today`'s month.
 * Names, addresses and amounts are made up.
 */
export const SEED_MONTHS = 6;

const euros = (value: number) => Math.round(value * 100);

type CategoryKey = DefaultCategoryKey;
const CATEGORIES = DEFAULT_CATEGORIES;

export interface SeedOptions {
  /** Full months before `today`'s month to fill in. Default 6. */
  months?: number;
}

export function createSeedData(today: string = todayIso(), options: SeedOptions = {}): Snapshot {
  const n = Math.max(6, options.months ?? SEED_MONTHS);
  const currentMonth = today.slice(0, 7);
  const months = Array.from({ length: n }, (_, i) => addMonths(currentMonth, i - n));
  const firstDay = dayInMonth(months[0], 1);

  const cat = Object.fromEntries(
    Object.entries(CATEGORIES).map(([key, value]) => [
      key,
      { notExpense: false, limitedDeduction: false, ...value, id: newId() },
    ]),
  ) as Record<CategoryKey, Category>;

  const centro: Property = {
    id: newId(),
    name: "Piso Centro",
    address: "Calle del Ejemplo 12, 3º B, Valladolid",
    purchaseDate: "2019-03-15",
    acquisitionPrice: euros(168000),
    purchaseCosts: euros(14280),
    cadastralValue: euros(96400),
    constructionPercentage: 62,
    active: true,
  };
  const playa: Property = {
    id: newId(),
    name: "Apartamento Playa",
    address: "Avenida Ficticia 4, 1º A, Gandía",
    purchaseDate: "2022-06-01",
    acquisitionPrice: euros(129500),
    purchaseCosts: euros(11650),
    cadastralValue: euros(71200),
    constructionPercentage: 55,
    active: true,
  };

  const transactions: Transaction[] = [];
  const recurrings: Recurring[] = [];
  const seedEnd = dayInMonth(months[n - 1], 31);

  const categoryById = (id: string) => Object.values(cat).find((c) => c.id === id)!;
  const add = (t: Omit<Transaction, "id" | "recurringId" | "type" | "confirmed">, recurringId: string | null = null) => {
    transactions.push({ ...t, id: newId(), type: categoryById(t.categoryId).type, recurringId, confirmed: true });
  };

  /**
   * Recurring rule plus its (confirmed) transactions within the seed period.
   * Occurrences from the current month on are generated by the app as pending.
   */
  const recurring = (
    r: Omit<Recurring, "id" | "type" | "endDate" | "generatedUntil" | "day" | "startDate" | "kind" | "mortgage">,
    monthIndex: number,
    day: number,
    endDate: string | null = null,
  ) => {
    const startDate = dayInMonth(months[monthIndex], day);
    const rule: Recurring = {
      ...r, id: newId(), kind: "fijo", mortgage: null, type: categoryById(r.categoryId).type, day, startDate, endDate, generatedUntil: seedEnd,
    };
    recurrings.push(rule);
    for (const date of occurrencesBetween(rule, null, seedEnd)) {
      add({ date, amount: rule.amount, categoryId: rule.categoryId, propertyId: rule.propertyId, concept: rule.concept }, rule.id);
    }
  };

  const monthly = (concept: string, amount: number, key: CategoryKey, property: Property | null, day: number) =>
    recurring({ concept, amount: euros(amount), categoryId: cat[key].id, propertyId: property?.id ?? null, frequency: "mensual" }, 0, day);
  const yearly = (monthIndex: number, day: number, amount: number, key: CategoryKey, property: Property, concept: string) =>
    recurring({ concept, amount: euros(amount), categoryId: cat[key].id, propertyId: property.id, frequency: "anual" }, monthIndex, day);

  monthly("Alquiler Piso Centro", 950, "alquiler", centro, 1);
  monthly("Alquiler Apartamento Playa", 780, "alquiler", playa, 5);
  monthly("Comunidad Piso Centro", 65, "comunidad", centro, 10);
  monthly("Comunidad Apartamento Playa", 48, "comunidad", playa, 10);
  monthly("Nómina", 2350, "nomina", null, 28);

  // Yearly charges (IBI in two instalments for Piso Centro).
  yearly(0, 20, 412.37, "ibi", centro, "IBI Piso Centro (1er plazo)");
  yearly(3, 20, 412.36, "ibi", centro, "IBI Piso Centro (2º plazo)");
  yearly(2, 15, 538.9, "ibi", playa, "IBI Apartamento Playa");
  yearly(1, 7, 286.4, "seguroHogar", centro, "Seguro hogar Piso Centro");
  yearly(4, 7, 214.75, "seguroHogar", playa, "Seguro hogar Apartamento Playa");
  yearly(1, 8, 315, "seguroImpago", centro, "Seguro de impago Piso Centro");
  yearly(2, 18, 96.8, "basuras", playa, "Tasa de basuras Apartamento Playa");

  // Quarterly fee, and a personal subscription with an end date (a year from its start).
  recurring({ concept: "Gestoría alquileres (trimestral)", amount: euros(60.5), categoryId: cat.gestoria.id, propertyId: centro.id, frequency: "trimestral" }, 0, 20);
  recurring(
    { concept: "Plataforma de streaming", amount: euros(12.99), categoryId: cat.ocio.id, propertyId: null, frequency: "mensual" },
    1,
    15,
    dayInMonth(addMonths(months[1], 11), 15),
  );

  // Mortgages: each installment split into interest (deductible) and principal (not an expense).
  const mortgage = (
    property: Property,
    principal: number,
    annualRate: number,
    installments: number,
    startDate: string,
    adjustments: MortgageAdjustment[] = [],
  ) => {
    const day = Number(startDate.slice(8, 10));
    const endDate = dayInMonth(addMonths(startDate.slice(0, 7), installments - 1), day);
    const rule: Recurring = {
      id: newId(),
      kind: "hipoteca",
      concept: `Hipoteca ${property.name}`,
      amount: annuityPayment(euros(principal), annualRate, installments),
      type: "gasto",
      categoryId: cat.intereses.id,
      propertyId: property.id,
      frequency: "mensual",
      day,
      startDate,
      endDate,
      generatedUntil: seedEnd,
      mortgage: {
        principal: euros(principal), annualRate, installments, interestMethod: "mensual", principalCategoryId: cat.capital.id, adjustments,
      },
    };
    recurrings.push(rule);
    const plan = planOf(rule);
    for (const date of occurrencesBetween(rule, dayBefore(firstDay), seedEnd)) {
      for (const t of occurrenceTransactions(rule, date, true, plan)) transactions.push({ ...t, id: newId() });
    }
  };
  // The bank rounds this one's installment up to 563 €: an adjustment from the 4th seed month.
  mortgage(centro, 120000, 2.9, 300, "2019-04-02", [{ date: dayInMonth(months[3], 15), balance: null, payment: euros(563) }]);
  mortgage(playa, 95000, 3.4, 360, "2022-07-03");

  // One-off flat expenses.
  const flat = (monthIndex: number, day: number, amount: number, key: CategoryKey, property: Property, concept: string) =>
    add({ date: dayInMonth(months[monthIndex], day), amount: euros(amount), categoryId: cat[key].id, propertyId: property.id, concept });

  flat(2, 22, 180, "reparaciones", centro, "Fontanero: cambio de grifo y latiguillos");
  flat(4, 12, 345.5, "reparaciones", playa, "Pintura salón");
  flat(5, 25, 121, "gestoria", centro, "Gestoría: renovación contrato");
  flat(3, 6, 38.9, "suministros", playa, "Luz entre inquilinos");
  if (n >= 12) {
    flat(7, 9, 95, "reparaciones", centro, "Revisión anual de la caldera");
    flat(9, 14, 420, "reparaciones", playa, "Cambio de termo eléctrico");
    flat(10, 3, 54.2, "otrosPiso", centro, "Cerrajero: copia de llaves");
  }

  // Personal expenses.
  const personal: [number, number, number, CategoryKey, string][] = [];
  months.forEach((_, i) => {
    personal.push(
      [i, 3, 92.4 + i * 3.1, "alimentacion", "Supermercado"],
      [i, 17, 118.75 - i * 2.4, "alimentacion", "Supermercado"],
      [i, 9, 64.2 + (i % 3) * 7.5, "hogar", "Luz y gas"],
      [i, 11, 35, "hogar", "Fibra y móvil"],
      [i, 14, 45 + (i % 2) * 20, "transporte", "Gasolina"],
    );
  });
  // One-off personal expenses, repeated (with other amounts) every six months.
  for (let base = 0; base < n; base += 6) {
    const k = base / 6;
    personal.push(
      [base, 21, 58 + k * 12, "ocio", "Cena con amigos"],
      [base + 2, 26, 124.9, "ocio", k % 2 ? "Escapada fin de semana" : "Entradas concierto"],
      [base + 3, 4, 42 - k * 5, "salud", "Farmacia"],
      [base + 4, 19, 75, "salud", "Dentista: revisión"],
      [base + 5, 15, 39.99 + k * 20, "otrosPersonal", k % 2 ? "Regalos de Navidad" : "Regalo cumpleaños"],
    );
  }
  for (const [i, day, amount, key, concept] of personal.filter(([i]) => i < n)) {
    add({ date: dayInMonth(months[i], day), amount: euros(amount), categoryId: cat[key].id, propertyId: null, concept });
  }

  // Investments: monthly snapshots at the end of each seed month.
  const assets: Asset[] = [];
  const assetSnapshots: AssetSnapshot[] = [];
  const [typeRv, typeRf, typeLiq, typeRe] = DEFAULT_ASSET_TYPES.map((t): AssetType => ({ ...t, id: newId() }));
  const newAsset = (name: string, kind: Asset["kind"], type: AssetType | null, propertyId: string | null = null) => {
    const a: Asset = { id: newId(), name, kind, propertyId, assetTypeId: type?.id ?? null, active: true };
    assets.push(a);
    return a;
  };
  const snapshot = (a: Asset, i: number, value: number, purchaseValue: number | null = null, fiscalCost: number | null = null) =>
    assetSnapshots.push({
      id: newId(),
      assetId: a.id,
      date: dayInMonth(months[i], 31),
      value: euros(value),
      purchaseValue: purchaseValue === null ? null : euros(purchaseValue),
      fiscalCost: fiscalCost === null ? null : euros(fiscalCost),
    });

  // Transferred from another fund: fiscal cost (original contributions) below purchase value.
  const rv = newAsset("Fondo indexado RV global", "fondo", typeRv);
  const rf = newAsset("Fondo indexado RF europea", "fondo", typeRf);
  const etf = newAsset("ETF S&P 500", "etf", typeRv);
  const cash = newAsset("Cuenta remunerada", "efectivo", typeLiq);
  // Fictitious market moves: steady drift plus some ups and downs (deterministic).
  const wave = (i: number, amplitude: number, phase: number) => amplitude * Math.sin(i * 1.3 + phase);
  const round2 = (x: number) => Math.round(x * 100) / 100;
  const rvValues = months.map((_, i) => round2((30000 + 300 * i) * (1.06 + 0.009 * i + wave(i, 0.025, 0))));
  const rfValues = months.map((_, i) => round2((15000 + 100 * i) * (1.008 + 0.0015 * i + wave(i, 0.004, 1))));
  const etfValues = months.map((_, i) => round2(8000 * (1.05 + 0.011 * i + wave(i, 0.03, 2))));
  const cashValues = months.map((_, i) => round2(12000 + 140 * i + wave(i, 420, 0.5)));
  months.forEach((_, i) => {
    // 300 €/month into the equity fund and 100 €/month into the bond fund.
    snapshot(rv, i, rvValues[i], 30000 + 300 * i, 22000 + 300 * i);
    snapshot(rf, i, rfValues[i], 15000 + 100 * i, 15000 + 100 * i);
    snapshot(etf, i, etfValues[i], i === 0 ? 8000 : null);
    snapshot(cash, i, cashValues[i]);
  });
  const centroAsset = newAsset(centro.name, "inmobiliario", typeRe, centro.id);
  // Left without a type on purpose, to show «Sin tipo» in the charts.
  const playaAsset = newAsset(playa.name, "inmobiliario", null, playa.id);
  snapshot(centroAsset, 0, 245000);
  snapshot(playaAsset, 0, 168000);
  // A later valuation, when the period is long enough.
  if (n >= 12) {
    snapshot(centroAsset, n - 1, 251500);
    snapshot(playaAsset, n - 1, 171200);
  }

  const portfolio = (name: string, parentId: string | null, assetIds: string[]): Portfolio => ({ id: newId(), name, parentId, assetIds });
  const patrimonio = portfolio("Patrimonio", null, [cash.id, centroAsset.id, playaAsset.id]);
  const indexada = portfolio("Indexada", patrimonio.id, [etf.id]);
  const bogle = portfolio("Bogle", indexada.id, [rv.id, rf.id]);
  // An asset can be in several portfolios: the equity fund is also here.
  const rentaVariable = portfolio("Renta variable", null, [rv.id, etf.id]);

  return {
    properties: [centro, playa],
    categories: Object.values(cat),
    transactions,
    recurrings,
    assetTypes: [typeRv, typeRf, typeLiq, typeRe],
    assets,
    assetSnapshots,
    portfolios: [patrimonio, indexada, bogle, rentaVariable],
  };
}

/** `YYYY-MM-DD` of the previous day. */
function dayBefore(date: string): string {
  const d = new Date(date + "T00:00:00Z");
  d.setUTCDate(d.getUTCDate() - 1);
  return d.toISOString().slice(0, 10);
}
